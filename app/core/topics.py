def topics_for(subject: str) -> list[Topic]:
    """Темы предмета (пустой список — предмета нет в каталоге)."""
    return TOPICS.get(subject, [])


def get_topic(subject: str, code: str) -> Topic | None:
    """Тема по номеру или None."""
    for item in topics_for(subject):
        if item.code == code:
            return item
    return None


def topic_label(subject: str, code: str) -> str:
    """«05. Линейные, квадратные…» или «Без темы»."""
    item = get_topic(subject, code)
    return f"{item.code}. {item.name}" if item else t("Без темы")
