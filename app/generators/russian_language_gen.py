_VOWELS = "аеёиоуыэюя"


def _wrong_stress(rng: random.Random, word: str) -> str:
    plain = word.lower()
    right = next(i for i, ch in enumerate(word) if ch.isupper())
    others = [i for i, ch in enumerate(plain) if ch in _VOWELS and i != right]
    if not others:
        raise SkipQuestion
    i = rng.choice(others)
    return plain[:i] + plain[i].upper() + plain[i + 1:]


@topic("01")
def stress(rng: random.Random) -> dict:
    correct = rng.choice(STRESS)
    others = rng.sample([w for w in STRESS if w != correct], 3)
    wrong = [_wrong_stress(rng, w) for w in others]
    text = "В каком слове ударение поставлено верно (ударная гласная — заглавная)? " + "/".join(
        sorted([correct.lower()] + [w.lower() for w in others]))
    return single(rng, text, correct, wrong,
                  f"Верно: {correct}. В остальных словах правильно: {', '.join(others)}.")


