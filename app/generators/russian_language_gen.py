@topic("01")
def spelling(rng: random.Random) -> dict:
    right, _ = rng.choice(SPELLING)
    others = rng.sample([p for p in SPELLING if p[0] != right], 3)
    wrong = [bad for _, bad in others]
    text = "Укажите слово, написанное без ошибки: " + ", ".join(sorted([right] + wrong)) + "."
    expl = f"Правильно: {right}. Ошибки исправлены так: " + ", ".join(f"{bad} → {good}" for good, bad in others) + "."
    return single(rng, text, right, wrong, expl)


