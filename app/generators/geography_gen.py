def scale(rng):
    denom = rng.choice([10_000, 25_000, 50_000, 100_000, 200_000, 500_000, 1_000_000])
    cm = rng.choice([1, 2, 2.5, 3, 4, 5, 6, 8, 10, 12])
    meters = denom * cm / 100
    if meters >= 1000:
        value, unit = meters / 1000, "км"
    else:
        value, unit = meters, "м"
    text = f"Расстояние на карте масштаба 1:{num(denom)} равно {num(cm)} см. Каково расстояние на местности?"
    expl = (f"Масштаб 1:{num(denom)} означает, что 1 см на карте — это {num(denom)} см = {num(denom / 100)} м "
            f"на местности. {num(cm)}·{num(denom / 100)} м = {num(meters)} м" +
            (f" = {num(value)} км." if unit == "км" else "."))
    wrong = [value * 10, value / 10, value * 100, value + cm]
    return single(rng, text, f"{num(value)} {unit}", number_distractors(rng, value, wrong, f" {unit}"), expl)


def altitude_temperature(rng):
    t0 = rng.randint(10, 35)
    h = rng.choice([1000, 1500, 2000, 2500, 3000, 3500, 4000, 5000])
    t = t0 - 6 * h / 1000
    text = (f"У подножия горы температура воздуха +{t0} °C. Какой будет температура на высоте {num(h)} м? "
            f"(с подъёмом на 1 км температура понижается на 6 °C)")
    expl = f"Понижение: {num(h / 1000)} км·6 °C = {num(6 * h / 1000)} °C. {t0} − {num(6 * h / 1000)} = {num(t)} °C."
    return single(rng, text, f"{num(t)} °C",
                  number_distractors(rng, t, [t0 + 6 * h / 1000, t0 - h / 100, t0 - 6, -t], " °C"), expl)


def time_zones(rng):
    lon1 = rng.choice([0, 15, 30, 45, 60, 75, 90, 105, 120, 135])
    lon2 = rng.choice([l for l in (0, 15, 30, 45, 60, 75, 90, 105, 120, 135) if l != lon1])
    hour = rng.randint(6, 16)
    diff = (lon2 - lon1) // 15
    result = (hour + diff) % 24
    text = (f"В пункте на {lon1}° в. д. местное время {hour}:00. Сколько времени в пункте на {lon2}° в. д.? "
            f"(используйте поясное время: 15° = 1 час)")
    direction = "восточнее, время больше" if diff > 0 else "западнее, время меньше"
    expl = f"Разница долгот {abs(lon2 - lon1)}° = {abs(diff)} ч. Второй пункт {direction}: {hour} {'+' if diff > 0 else '−'} {abs(diff)} = {result}:00."
    wrong = [f"{(hour - diff) % 24}:00", f"{(hour + diff + 1) % 24}:00", f"{(hour + diff - 1) % 24}:00",
             f"{(hour + 2 * diff) % 24}:00"]
    return single(rng, text, f"{result}:00", wrong, expl)


def density(rng):
    area = rng.choice([100, 150, 200, 250, 300, 400, 500, 800]) * 1000
    dens = rng.choice([2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 25])
    population = area * dens
    text = f"Площадь территории {num(area)} км², население {num(population)} человек. Найдите плотность населения."
    expl = f"Плотность = население : площадь = {num(population)} : {num(area)} = {dens} чел./км²."
    return single(rng, text, f"{dens} чел./км²",
                  number_distractors(rng, dens, [dens * 10, dens * 2, dens + 5, area // population if population else 1],
                                     " чел./км²"), expl)


