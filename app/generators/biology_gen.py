def monohybrid(rng):
    dom, rec, D, r = rng.choice(_TRAITS)
    cross = rng.choice(["AaxAa", "Aaxaa", "AAxaa"])
    if cross == "AaxAa":
        text = (f"Скрестили двух гетерозигот ({D}{r} × {D}{r}); признак «{dom}» доминирует над признаком «{rec}». "
                "Каково расщепление по фенотипу?")
        answer, expl = "3 : 1", f"Генотипы потомства: 1 {D}{D} : 2 {D}{r} : 1 {r}{r}. Фенотипы: 3 с признаком «{dom}» : 1 с признаком «{rec}»."
        wrong = ["1 : 2 : 1", "1 : 1", "9 : 3 : 3 : 1", "100% доминантный признак"]
    elif cross == "Aaxaa":
        text = f"Скрестили {D}{r} × {r}{r}; признак «{dom}» доминирует над признаком «{rec}». Каково расщепление по фенотипу?"
        answer, expl = "1 : 1", f"Потомство: {D}{r} и {r}{r} поровну — 1 : 1 (анализирующее скрещивание)."
        wrong = ["3 : 1", "1 : 2 : 1", "100% доминантный признак", "9 : 3 : 3 : 1"]
    else:
        text = f"Скрестили {D}{D} × {r}{r}; признак «{dom}» доминирует над признаком «{rec}». Каким будет потомство F₁?"
        answer, expl = "100% доминантный признак", f"Все потомки {D}{r} — единообразие первого поколения (I закон Менделя)."
        wrong = ["3 : 1", "1 : 1", "1 : 2 : 1", "9 : 3 : 3 : 1"]
    return single(rng, text, answer, wrong, expl)


def probability_recessive(rng):
    dom, rec, D, r = rng.choice(_TRAITS)
    total = rng.choice([40, 80, 120, 160, 200, 400, 800])
    text = (f"При скрещивании гетерозигот {D}{r} × {D}{r} получили {total} потомков. "
            f"Сколько из них ожидается с рецессивным признаком «{rec}»?")
    value = total // 4
    expl = f"Рецессивный признак проявляется только у {r}{r} — это 1/4 потомства: {total} : 4 = {value}."
    return single(rng, text, str(value), number_distractors(rng, value, [total // 2, total * 3 // 4, total // 3]), expl)


def genetics_context(rng):
    dom, rec, D, r = rng.choice(_TRAITS)
    total = rng.choice([100, 200, 400, 600, 800])
    context = (f"Признак «{dom}» ({D}) доминирует над признаком «{rec}» ({r}). Скрестили две гетерозиготные "
               f"особи и получили {total} потомков.")
    kind = rng.choice(["hetero", "dominant"])
    if kind == "hetero":
        text = f"Сколько гетерозигот ожидается среди {total} потомков {D}{r} × {D}{r}?"
        value, expl = total // 2, f"Генотипы 1 {D}{D} : 2 {D}{r} : 1 {r}{r}, гетерозиготы — половина: {total // 2}."
        wrong = [total // 4, total * 3 // 4, total]
    else:
        text = f"Сколько потомков {D}{r} × {D}{r} из {total} будут с признаком «{dom}»?"
        value, expl = total * 3 // 4, f"Доминантный признак у {D}{D} и {D}{r} — это 3/4: {total * 3 // 4}."
        wrong = [total // 4, total // 2, total]
    return single(rng, text, str(value), number_distractors(rng, value, wrong), expl, context=context)


def genotype_matching(rng):
    dom, rec, D, r = rng.choice(_TRAITS)
    pairs = rng.sample([(f"{D}{D}", "гомозигота по доминантному признаку"), (f"{D}{r}", "гетерозигота"),
                        (f"{r}{r}", "гомозигота по рецессивному признаку")], 2)
    extra = ["гемизигота", "полиплоид", "мутант"]
    text = f"Установите соответствие между генотипом и его названием: 1) {pairs[0][0]}; 2) {pairs[1][0]}."
    expl = f"{pairs[0][0]} — {pairs[0][1]}; {pairs[1][0]} — {pairs[1][1]}."
    return matching(rng, text, pairs, rng.sample(extra, 2), expl)


