_COMPLEMENT = {"А": "Т", "Т": "А", "Г": "Ц", "Ц": "Г"}
_RNA = {"А": "У", "Т": "А", "Г": "Ц", "Ц": "Г"}


def dna_complement(rng):
    strand = "".join(rng.choice("АТГЦ") for _ in range(rng.randint(8, 12)))
    if rng.random() < 0.5:
        answer = "".join(_COMPLEMENT[n] for n in strand)
        text = f"Участок одной цепи ДНК: {strand}. Какова последовательность второй (комплементарной) цепи?"
        wrong = [strand[::-1], "".join(_RNA[n] for n in strand), answer[::-1],
                 "".join({"А": "Г", "Г": "А", "Т": "Ц", "Ц": "Т"}[n] for n in strand)]
        expl = f"По принципу комплементарности А связывается с Т, а Г — с Ц. Вторая цепь: {answer}."
    else:
        answer = "".join(_RNA[n] for n in strand)
        text = f"Участок цепи ДНК: {strand}. Какова последовательность иРНК, синтезированной на этой цепи?"
        wrong = ["".join(_COMPLEMENT[n] for n in strand), strand, answer[::-1], strand.replace("Т", "У")]
        expl = f"В РНК вместо тимина урацил: А → У, Т → А, Г → Ц, Ц → Г. иРНК: {answer}."
    return single(rng, text, answer, wrong, expl)


def chargaff(rng):
    a = rng.choice([10, 12, 15, 18, 20, 22, 24, 25, 28, 30, 32, 35, 40])
    g = (100 - 2 * a) // 2
    given, ask = rng.choice([("аденина", "гуанина"), ("тимина", "цитозина"), ("аденина", "тимина")])
    answer = a if ask == "тимина" else g
    text = f"В молекуле ДНК {a}% нуклеотидов приходится на долю {given}. Какова доля {ask}?"
    expl = (f"По правилу Чаргаффа А = Т и Г = Ц. А + Т = 2·{a} = {2 * a}%, на Г + Ц остаётся {100 - 2 * a}%, "
            f"значит Г = Ц = {g}%. Доля {ask}: {answer}%.")
    return single(rng, text, f"{answer}%",
                  number_distractors(rng, answer, [100 - a, 100 - 2 * a, 50 - a / 2, a if answer != a else g], "%"),
                  expl)


def codons(rng):
    n = rng.randint(20, 300)
    kind = rng.choice(["nucleotides", "codons", "dna"])
    if kind == "nucleotides":
        text = (f"Белок состоит из {n} {plural(n, 'аминокислоты', 'аминокислот', 'аминокислот')}. "
                "Сколько нуклеотидов в кодирующем участке иРНК (без стоп-кодона)?")
        value, expl = 3 * n, f"Каждую аминокислоту кодирует триплет — 3 нуклеотида: {n}·3 = {3 * n}."
        wrong = [n, 6 * n, n // 3 if n % 3 == 0 else n + 3, 2 * n]
    elif kind == "codons":
        text = f"Участок иРНК содержит {3 * n} нуклеотидов. Сколько аминокислот он кодирует (без стоп-кодона)?"
        value, expl = n, f"Один кодон — 3 нуклеотида: {3 * n} : 3 = {n} аминокислот."
        wrong = [3 * n, 9 * n, n * 2, n + 3]
    else:
        text = (f"Белок состоит из {n} {plural(n, 'аминокислоты', 'аминокислот', 'аминокислот')}. "
                f"Сколько нуклеотидов в двухцепочечном участке ДНК, "
                f"который его кодирует (без стоп-кодона)?")
        value, expl = 6 * n, f"В одной цепи {n}·3 = {3 * n} нуклеотидов, в двух цепях — {6 * n}."
        wrong = [3 * n, n, 2 * n, 9 * n]
    return single(rng, text, str(value), number_distractors(rng, value, wrong), expl)


