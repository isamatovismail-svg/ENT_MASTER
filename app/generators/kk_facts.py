def build(facts: list[Fact], **kwargs) -> dict:
    """facts.build, где у каждого факта есть вопрос «чем известен» (формулировка — what_phrases группы)."""
    return _build(facts=[f if f.what else replace(f, what="?") for f in facts], **kwargs)


def years(rows: list[tuple[int, str, str, str]], group: str = "жыл") -> list[Fact]:
    """(год, вопрос «когда», событие, тема) → факты группы «жыл»."""
    return [Fact(str(year), event, question, "", group, topic=code) for year, question, event, code in rows]


